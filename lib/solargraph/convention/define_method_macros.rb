# frozen_string_literal: true

module Solargraph
  module Convention
    # Maps the methods that macros create with define_method, e.g.,
    # +add_flash_types :alert+ defines +#alert+. See Macro for what counts as
    # a macro.
    class DefineMethodMacros < Base
      autoload :Macro, 'solargraph/convention/define_method_macros/macro'

      module NodeProcessors
        # Records a method's macros on its pin when its body calls
        # define_method or define_singleton_method. Each call is examined
        # once, with only its enclosing blocks, so mapping stays linear.
        class DefinerNode < Parser::NodeProcessor::Base
          # @return [Boolean] continue processing the next processor of the same node.
          def process
            return true unless Macro::DEFINERS.key?(node.children[1])
            # @type [::Array<::Parser::AST::Node>]
            blocks = []
            closure = region.closure
            while closure.is_a?(Pin::Block)
              return true if blocks.length == Macro::MAX_BLOCK_DEPTH
              blocks.unshift closure.node
              closure = closure.closure
            end
            return true unless closure.is_a?(Pin::Method)
            record closure.call_site_templates, Macro.from_send(node, closure.node, blocks)
            true
          end

          private

          # @param templates [::Array<Object>]
          # @param macro [Macro, nil]
          # @return [void]
          def record templates, macro
            return if macro.nil?
            return if templates.any? { |t| t.is_a?(Macro) && t.key == macro.key }
            templates.push macro
          end
        end
      end

      # @param api_map [ApiMap]
      # @return [Environ]
      def catalog api_map
        macro_pins = api_map.call_site_template_pins.transform_values do |pins|
          pins.select { |pin| pin.call_site_templates.any? { |t| t.is_a?(Macro) } }
        end
        macro_pins.reject! { |_name, pins| pins.empty? }
        return EMPTY_ENVIRON if macro_pins.empty?
        Environ.new(pins: api_map.source_maps.flat_map { |map| call_pins(api_map, map, macro_pins) })
      end

      private

      # The methods generated by calls at class level to macros in a source,
      # e.g., +add_flash_types :alert+.
      #
      # @param api_map [ApiMap]
      # @param source_map [SourceMap]
      # @param macro_pins [Hash{String => Array<Pin::Method>}]
      # @return [Array<Pin::Method>]
      def call_pins api_map, source_map, macro_pins
        source_map.method_call_nodes.flat_map do |node|
          next [] unless node.type == :send
          candidates = macro_pins[node.children[1].to_s]
          next [] unless candidates
          receiver = node.children[0]
          next [] unless receiver.nil? || receiver.type == :self
          namespace = class_level_namespace(source_map.locate_closure_pin(node.location.line, node.location.column))
          next [] unless namespace
          match = candidates.find { |pin| macro_for?(api_map, pin, namespace) }
          next [] unless match
          range = Range.from_node(node)
          next [] unless range
          location = Location.new(source_map.filename, range)
          # @type [Array<Macro>]
          macros = match.call_site_templates.grep(Macro).uniq(&:key)
          # @type [Array<Pin::Method>]
          pins = macros.flat_map { |macro| macro.generate_pins(node, namespace, location) }
          pins.uniq { |pin| [pin.scope, pin.name] }
        end
      end

      # The namespace whose body a closure belongs to, or nil if the closure
      # is in a method, where self is not the namespace.
      #
      # @param closure [Pin::Closure, nil]
      # @return [Pin::Namespace, nil]
      def class_level_namespace closure
        closure = closure.closure while closure.is_a?(Pin::Block)
        closure if closure.is_a?(Pin::Namespace)
      end

      # True if a call to the macro's name in the namespace's body calls the
      # macro. Besides the namespace's own class methods, this accepts macros
      # in modules nested in the namespace, e.g., an ActiveSupport::Concern's
      # ClassMethods called from its +included+ block.
      #
      # @param api_map [ApiMap]
      # @param pin [Pin::Method]
      # @param namespace [Pin::Namespace]
      def macro_for? api_map, pin, namespace
        pin.namespace.start_with?("#{namespace.path}::") ||
          api_map.get_complex_type_methods(namespace.return_type).include?(pin)
      end
    end
  end
end
